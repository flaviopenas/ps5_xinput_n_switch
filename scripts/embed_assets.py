"""Embed local manager assets or an ELF as C arrays; no external downloads."""
import argparse
import hashlib
from pathlib import Path
def array(name, data, terminate=True):
    if terminate:
        data += b'\0'
    return f'static const unsigned char {name}[] = {{\n' + ',\n'.join(
        ','.join(f'0x{b:02x}' for b in data[i:i+24]) for i in range(0,len(data),24)) + '\n};\n'
def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('output',type=Path)
    p.add_argument('--elf',type=Path)
    a=p.parse_args()
    if a.elf:
        content=array('manager_service_elf',a.elf.read_bytes(),False)
    else:
        css=Path('manager/app.css').read_bytes()
        js=Path('manager/app.js').read_bytes()
        html=Path('manager/index.html').read_bytes()
        for asset,data in ((b'app.css',css),(b'app.js',js)):
            html=html.replace(b'/'+asset+b'"',b'/'+asset+b'?v='+hashlib.sha256(data).hexdigest()[:12].encode()+b'"')
        content=''.join(array(name,data) for name,data in (
            ('manager_html',html),('manager_css',css),('manager_js',js)))
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text('/* Generated by scripts/embed_assets.py. */\n'+content)
if __name__=='__main__':main()
